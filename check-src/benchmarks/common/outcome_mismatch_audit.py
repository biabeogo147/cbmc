#!/usr/bin/env python3
"""Write verdicts for verification-outcome mismatch audit cases.

Inputs:
  - check-src/benchmarks/results/audit/benchmark-inventory.csv.
  - Evidence CSV/logs generated by run_evidence_case.py.

Output:
  - check-src/benchmarks/results/audit/outcome-mismatch-audit.csv.

This file records the Phase 3-5 human-audited verdict policy. The verdicts are
grounded in the preserved trace logs and source normalization contracts; they
are intentionally separate from benchmark timing reports.
"""

import argparse
import csv
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
BENCHMARK_DIR = SCRIPT_DIR.parent
DEFAULT_INVENTORY = BENCHMARK_DIR / "results" / "audit" / "benchmark-inventory.csv"
DEFAULT_RESULTS = BENCHMARK_DIR / "results" / "audit"
DEFAULT_WORK = BENCHMARK_DIR / "work" / "audit"
DEFAULT_OUTPUT = BENCHMARK_DIR / "results" / "audit" / "outcome-mismatch-audit.csv"
FIELDS = [
    "category",
    "suite",
    "case",
    "logical_case_id",
    "stock_summary",
    "improved_summary",
    "verdict",
    "correct_variant",
    "action",
    "evidence",
    "stock_property",
    "improved_property",
]


def load_inventory(path):
    """Load outcome mismatch inventory rows.

    Args:
        path: Inventory CSV path.

    Returns:
        Rows that are not no-injection audit rows.
    """
    with path.open(newline="", encoding="utf-8", errors="replace") as csv_file:
        return [row for row in csv.DictReader(csv_file) if row.get("needs_no_injection_audit") != "true"]


def read_text(path):
    """Read a file when it exists.

    Args:
        path: File path.

    Returns:
        File text, or an empty string when missing.
    """
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8", errors="replace")


def evidence_csv(results_dir, suite, case):
    """Return evidence CSV rows for one case.

    Args:
        results_dir: Audit results directory.
        suite: Original suite name.
        case: Case name.

    Returns:
        List of CSV rows.
    """
    path = results_dir / f"{suite}__{case}__evidence.csv"
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8", errors="replace") as csv_file:
        return list(csv.DictReader(csv_file))


def first_verify_summary(rows, variant):
    """Return the first verify summary for a variant.

    Args:
        rows: Evidence CSV rows.
        variant: Variant name.

    Returns:
        Summary string or EXIT_<code>.
    """
    for row in rows:
        if row.get("variant") == variant and row.get("phase") == "verify":
            summary = row.get("summary") or ""
            return summary if summary else f"EXIT_{row.get('exit_code', '')}"
    return ""


def first_verify_log(work_dir, suite, case, variant):
    """Return the first verify log text for a case variant.

    Args:
        work_dir: Audit work directory.
        suite: Original suite name.
        case: Case name.
        variant: Variant name.

    Returns:
        Log text, or empty string.
    """
    pattern = f"{suite}__{case}__evidence.{case}.{variant}.verify.measure.1.log"
    path = work_dir / "logs" / pattern
    return read_text(path)


def violated_property(log_text):
    """Extract the violated property block from a CBMC log.

    Args:
        log_text: Verify log text.

    Returns:
        Compact violated-property text.
    """
    lines = log_text.splitlines()
    for index, line in enumerate(lines):
        if "Violated property:" in line:
            return " ".join(item.strip() for item in lines[index : index + 4] if item.strip())
    if "we don't support nesting of atomic sections" in log_text:
        for line in lines:
            if "we don't support nesting of atomic sections" in line:
                return line.strip()
    for index, line in enumerate(lines):
        if ": FAILURE" not in line:
            continue
        function_line = ""
        for previous in reversed(lines[:index]):
            if " function " in previous:
                function_line = previous.strip()
                break
        return " ".join(item for item in [function_line, line.strip()] if item)
    return ""


def interleaving_counts(work_dir, suite, case):
    """Return original/filtered interleaving counts when evidence exists.

    Args:
        work_dir: Audit work directory.
        suite: Original suite name.
        case: Case name.

    Returns:
        Tuple of count strings.
    """
    evidence_dir = work_dir / f"{suite}__{case}__evidence"
    if not evidence_dir.exists():
        return "", ""
    original = next(evidence_dir.rglob("improved_pipeline_interleaving_pipeline.json"), None)
    filtered = next(evidence_dir.rglob("improved_pipeline_interleaving_pipeline.filtered.json"), None)
    return count_json_interleavings(original), count_json_interleavings(filtered)


def count_json_interleavings(path):
    """Count interleaving entries in a JSON file.

    Args:
        path: JSON path or None.

    Returns:
        Count as string, or empty string.
    """
    if not path:
        return ""
    try:
        import json

        return str(len(json.loads(path.read_text(encoding="utf-8", errors="replace")).get("interleaving", [])))
    except Exception:
        return ""


def has_tool_or_model_error(summary, property_text):
    """Return whether a verification result is blocked by an invalid model/tool error.

    Args:
        summary: Verify summary text.
        property_text: Extracted violated-property text.

    Returns:
        True when the result did not reach a trustworthy verification verdict.
    """
    text = f"{summary or ''} {property_text or ''}"
    return (
        "no body for function" in text
        or "we don't support nesting of atomic sections" in text
        or "CBMC_UNSUPPORTED_CONCURRENCY" in text
    )


def verdict_for(row, stock_summary, improved_summary, stock_property, improved_property, original_count, filtered_count):
    """Return verdict, correct variant, action, and evidence for one case.

    Args:
        row: Inventory row.
        stock_summary: Stock verify summary.
        improved_summary: Improved verify summary.
        stock_property: Stock violated property block.
        improved_property: Improved violated property block.
        original_count: Original interleaving count.
        filtered_count: Filtered interleaving count.

    Returns:
        Tuple of verdict, correct variant, action, evidence.
    """
    suite = row["suite"]
    case = row["case"]
    if suite in {"local-smoke", "osek-local"}:
        return (
            "improved_correct",
            "improved_pipeline",
            "keep_benchmark_diagnostic_stock_model_too_weak",
            "Improved trace reaches injected ISR/task perturbation; simple benchmark docs expect the injected pipeline to fail.",
        )
    if suite == "intabs-large" and row["category"] == "Verification Failed vs Successful":
        return (
            "improved_correct",
            "improved_pipeline",
            "keep_benchmark_diagnostic_stock_overapproximates_non_atomic_async_threads",
            f"Improved keeps ISR/task entry atomic and has filtered interleavings {filtered_count}/{original_count}; stock failure is an async-thread interleaving into {stock_property}.",
        )
    if suite == "intabs-large" and case == "sc520wdt-2":
        return (
            "improved_correct",
            "improved_pipeline",
            "keep_benchmark_diagnostic_stock_model_too_weak",
            f"Improved injected closer/writer interleavings and reaches {improved_property}; stock baseline proves without that injected ISR ordering.",
        )
    if suite == "intabs-large" and case == "wdt-pci-2":
        if has_tool_or_model_error(stock_summary, stock_property) or has_tool_or_model_error(
            improved_summary, improved_property
        ):
            return (
                "both_need_fix",
                "none",
                "fix_wdt_pci_2_model_or_nested_atomic_before_correctness_comparison",
                f"At least one side is still blocked by model/tool evidence. Stock: {stock_summary} {stock_property}; improved: {improved_summary} {improved_property}.",
            )
        return (
            "pending_manual_review",
            "unknown",
            "inspect_wdt_pci_2_fresh_trace",
            f"Fresh wdt-pci-2 mismatch is no longer the known nested-atomic typo blocker. Stock: {stock_property}; improved: {improved_property}.",
        )
    if suite == "icbmc-timeout-30m-logger-stable":
        if has_tool_or_model_error(stock_summary, stock_property) or has_tool_or_model_error(
            improved_summary, improved_property
        ):
            return (
                "both_need_fix",
                "none",
                "fix_logger2_model_or_nested_atomic_before_correctness_comparison",
                f"At least one Logger2 side is still blocked by model/tool evidence. Stock: {stock_summary} {stock_property}; improved: {improved_summary} {improved_property}.",
            )
        if (
            stock_summary == "VERIFICATION FAILED"
            and improved_summary == "VERIFICATION SUCCESSFUL"
            and "numberOfRecords==pos+1" in stock_property
        ):
            return (
                "improved_correct",
                "improved_pipeline",
                "keep_benchmark_diagnostic_stock_non_atomic_async_interleaving",
                "Stock C_ASYNC_PROVER exposes an interleaving through task_measure that violates numberOfRecords==pos+1; improved checks the extracted ISR/task body as one atomic entry, matching the benchmark ISR-atomic contract.",
            )
        return (
            "pending_manual_review",
            "unknown",
            "inspect_logger2_fresh_trace",
            f"Fresh Logger2 mismatch is no longer the known missing-body/nested-atomic blocker. Stock: {stock_property}; improved: {improved_property}.",
        )
    return (
        "pending_manual_review",
        "unknown",
        "inspect_trace",
        "No verdict rule matched this case.",
    )


def build_rows(inventory, results_dir, work_dir):
    """Build outcome mismatch audit rows.

    Args:
        inventory: Inventory rows.
        results_dir: Audit results directory.
        work_dir: Audit work directory.

    Returns:
        List of audit rows.
    """
    rows = []
    for item in inventory:
        evidence_rows = evidence_csv(results_dir, item["suite"], item["case"])
        stock_summary = first_verify_summary(evidence_rows, "stock_cprover_async") or item["stock_summary"]
        improved_summary = first_verify_summary(evidence_rows, "improved_pipeline") or item["improved_summary"]
        stock_log = first_verify_log(work_dir, item["suite"], item["case"], "stock_cprover_async")
        improved_log = first_verify_log(work_dir, item["suite"], item["case"], "improved_pipeline")
        stock_property = violated_property(stock_log)
        improved_property = violated_property(improved_log)
        original_count, filtered_count = interleaving_counts(work_dir, item["suite"], item["case"])
        verdict, correct_variant, action, evidence = verdict_for(
            item,
            stock_summary,
            improved_summary,
            stock_property,
            improved_property,
            original_count,
            filtered_count,
        )
        rows.append(
            {
                "category": item["category"],
                "suite": item["suite"],
                "case": item["case"],
                "logical_case_id": item["logical_case_id"],
                "stock_summary": stock_summary,
                "improved_summary": improved_summary,
                "verdict": verdict,
                "correct_variant": correct_variant,
                "action": action,
                "evidence": evidence,
                "stock_property": stock_property,
                "improved_property": improved_property,
            }
        )
    return rows


def write_rows(rows, output_path):
    """Write audit rows to CSV.

    Args:
        rows: Audit row dictionaries.
        output_path: Destination CSV path.

    Returns:
        None.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", newline="", encoding="utf-8") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def main(argv=None):
    """CLI entry point.

    Args:
        argv: Optional command-line arguments.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--inventory", default=DEFAULT_INVENTORY)
    parser.add_argument("--results-dir", default=DEFAULT_RESULTS)
    parser.add_argument("--work", default=DEFAULT_WORK)
    parser.add_argument("--out", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    rows = build_rows(load_inventory(Path(args.inventory)), Path(args.results_dir), Path(args.work))
    write_rows(rows, Path(args.out))
    print(f"outcome mismatch audit rows: {len(rows)}")
    print(f"outcome mismatch audit: {Path(args.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
